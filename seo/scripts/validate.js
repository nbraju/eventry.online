#!/usr/bin/env node
'use strict';
/* Post-build QA: node scripts/validate.js --out <dir> */
const fs = require('fs');
const path = require('path');
const { readJson, MARKER } = require('../src/lib/util');

const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const outArg = args.includes('--out') ? args[args.indexOf('--out') + 1] : 'out';
const outDir = path.resolve(process.cwd(), outArg);
const site = readJson(path.join(ROOT, 'config/site.json'));
const errors = []; const warns = [];
const unesc = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");

function findPages(dir, depth = 0, acc = []) {
  if (depth > 3 || !fs.existsSync(dir)) return acc;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || e.name === 'node_modules') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) findPages(p, depth + 1, acc);
    else if (e.name === 'index.html' && fs.readFileSync(p, 'utf8').includes(MARKER)) acc.push(p);
  }
  return acc;
}

const files = findPages(outDir);
if (!files.length) { console.error('No generated pages found in ' + outDir); process.exit(1); }
const sm = fs.existsSync(path.join(outDir, 'sitemap.xml')) ? fs.readFileSync(path.join(outDir, 'sitemap.xml'), 'utf8') : '';
const smUrls = [...sm.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => unesc(m[1]));
if (!sm.includes(MARKER)) warns.push('sitemap.xml missing or not generated by this tool (skipped sitemap checks)');
if (new Set(smUrls).size !== smUrls.length) errors.push('sitemap.xml has duplicate URLs');
const robots = fs.existsSync(path.join(outDir, 'robots.txt')) ? fs.readFileSync(path.join(outDir, 'robots.txt'), 'utf8') : '';
if (robots.includes(MARKER) && !robots.includes(`Sitemap: ${site.baseUrl}/sitemap.xml`)) errors.push('robots.txt lacks the Sitemap line');

const texts = []; let indexableCount = 0;
for (const f of files) {
  const rel = path.relative(outDir, path.dirname(f)).split(path.sep).join('/');
  const url = `${site.baseUrl}/${rel}/`;
  const html = fs.readFileSync(f, 'utf8');
  const get = (re) => (html.match(re) || [])[1];
  const title = unesc(get(/<title>([^<]*)<\/title>/) || '');
  const desc = unesc(get(/<meta name="description" content="([^"]*)"/) || '');
  const canon = unesc(get(/<link rel="canonical" href="([^"]*)"/) || '');
  const robotsMeta = get(/<meta name="robots" content="([^"]*)"/) || '';
  const noindex = /noindex/.test(robotsMeta);
  const tag = (m) => `${rel}: ${m}`;
  if (title.length < 15 || title.length > 65) warns.push(tag(`title length ${title.length}`));
  if (desc.length < 70 || desc.length > 160) warns.push(tag(`meta description length ${desc.length}`));
  if ((html.match(/<h1[ >]/g) || []).length !== 1) errors.push(tag('must have exactly one <h1>'));
  if (canon !== url) errors.push(tag(`canonical ${canon} != ${url}`));
  const ld = get(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
  let graph = null;
  try { graph = JSON.parse(ld)['@graph']; } catch (e) { errors.push(tag('JSON-LD does not parse')); }
  if (graph) {
    const types = graph.map((g) => g['@type']);
    for (const t of ['CollectionPage', 'BreadcrumbList']) if (!types.includes(t)) errors.push(tag(`JSON-LD missing ${t}`));
    const faq = graph.find((g) => g['@type'] === 'FAQPage');
    const visible = (html.match(/<details>/g) || []).length;
    if (faq && faq.mainEntity.length !== visible) errors.push(tag(`FAQ in JSON-LD (${faq.mainEntity.length}) != visible FAQ (${visible})`));
    if (/aggregateRating|"review"|"priceRange"/.test(ld)) errors.push(tag('JSON-LD contains ratings/reviews/price data (not allowed: no real source)'));
  }
  if (noindex && smUrls.includes(url)) errors.push(tag('noindex page is listed in sitemap'));
  if (!noindex) { indexableCount++; if (sm.includes(MARKER) && !smUrls.includes(url)) errors.push(tag('indexable page missing from sitemap')); }
  const copy = [...html.matchAll(/<section class="s copy"[\s\S]*?<\/section>/g)].map((m) => m[0]).join(' ').replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').toLowerCase();
  const parts = rel.split('/');
  if (parts.length === 2) texts.push({ rel, cat: parts[1], copy });
}
for (const u of smUrls) {
  if (u === `${site.baseUrl}/`) continue;
  const rel = u.replace(site.baseUrl, '').replace(/^\/|\/$/g, '');
  if (!fs.existsSync(path.join(outDir, rel, 'index.html'))) errors.push(`sitemap lists ${u} but no file exists`);
}

// Near-duplicate check: 6-word shingles across pages of the same category
const shingles = (t) => { const w = t.split(' '); const s = new Set(); for (let i = 0; i + 6 <= w.length; i++) s.add(w.slice(i, i + 6).join(' ')); return s; };
let maxSim = 0; let pair = '';
for (let i = 0; i < texts.length; i++) for (let j = i + 1; j < texts.length; j++) {
  if (texts[i].cat !== texts[j].cat) continue;
  const a = shingles(texts[i].copy); const b = shingles(texts[j].copy);
  let inter = 0; for (const x of a) if (b.has(x)) inter++;
  const sim = inter / (a.size + b.size - inter || 1);
  if (sim > maxSim) { maxSim = sim; pair = `${texts[i].rel} vs ${texts[j].rel}`; }
  if (sim > 0.8) errors.push(`near-duplicate copy (${sim.toFixed(2)}): ${texts[i].rel} vs ${texts[j].rel}`);
  else if (sim > 0.6) warns.push(`high copy overlap (${sim.toFixed(2)}): ${texts[i].rel} vs ${texts[j].rel}. Add more local content to config/cities.json.`);
}

console.log(`Checked ${files.length} pages (${indexableCount} indexable), ${smUrls.length} sitemap URLs. Highest same-category copy overlap: ${maxSim.toFixed(2)}${pair ? ` (${pair})` : ''}`);
for (const w of warns) console.log('WARN  ' + w);
for (const e of errors) console.log('ERROR ' + e);
if (errors.length) process.exit(1);
console.log('OK');
